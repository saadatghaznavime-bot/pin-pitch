(() => {
  const agentPage = document.getElementById("agents");
  if (!agentPage) return;
  const panel = document.createElement("div");
  panel.className = "card";
  panel.style.marginTop = "18px";
  panel.innerHTML = `
    <div style="display:flex;align-items:center;justify-content:space-between;gap:10px">
      <div><div class="eyebrow">FREE VOICE DEMO</div><h2 style="font-size:18px;margin:5px 0">Talk to your agent</h2></div>
      <span class="status" id="voiceState">Ready</span>
    </div>
    <p class="muted">Try a no-API-cost voice demo using your browser's speech features.</p>
    <label class="field"><span>Select agent</span><select id="talkAgent" style="width:100%;padding:12px;border:1px solid #ead8cc;border-radius:11px;background:white"></select></label>
    <div id="talkTranscript" style="min-height:64px;max-height:180px;overflow:auto;background:#fff6f0;border-radius:12px;padding:10px;font-size:12px;color:#555;margin:12px 0">Your conversation will appear here.</div>
    <label class="field"><span>Or type a message</span><input id="freeVoiceText" type="text" placeholder="Ask about hours, pricing, bookings…"></label>
    <div style="display:flex;gap:8px">
      <button class="primary" id="talkStart" style="flex:1">🎙 Start speaking</button>
      <button class="ghost" id="talkSend">Send</button>
      <button class="ghost" id="talkStop" disabled>End</button>
    </div>
    <p class="muted" style="margin-top:10px">Free demo mode: replies are scripted, not generated by an AI model. Speech recognition is provided by your browser and may use its own online service. PIN&PITCH does not send audio to OpenAI in this mode.</p>`;
  const firstCard = agentPage.querySelector(".card");
  if (firstCard) firstCard.parentNode.insertBefore(panel, firstCard);
  else agentPage.appendChild(panel);

  let recognition = null, listening = false;
  const $ = id => document.getElementById(id);
  const state = value => $("voiceState").textContent = value;
  function log(who, text) {
    const box = $("talkTranscript");
    if (box.textContent === "Your conversation will appear here.") box.textContent = "";
    const line = document.createElement("p");
    line.style.margin = "5px 0";
    const strong = document.createElement("b"); strong.textContent = who + ": ";
    line.append(strong, document.createTextNode(text));
    box.appendChild(line); box.scrollTop = box.scrollHeight;
  }
  function localReply(raw) {
    const text = raw.toLowerCase();
    if (/^(hi|hello|hey|good morning|good afternoon)/.test(text)) return "Hello! Thanks for contacting us. I'm the PIN&PITCH demo assistant. How can I help you today?";
    if (/hour|open|close|timing/.test(text)) return "I can help with opening hours. This demo business has not been given its actual hours yet. Please tell me the business hours you want your agent to use.";
    if (/price|pricing|cost|how much|fee/.test(text)) return "I'd be happy to help with pricing. The demo has no price list configured yet. You can add your products and prices to the agent instructions.";
    if (/book|appointment|schedule|available|reservation/.test(text)) return "I can help with appointment requests. This demo is not connected to a live calendar yet. Please tell me your preferred date and time, and a team member can confirm it.";
    if (/human|person|representative|owner|staff|someone/.test(text)) return "Of course. I can arrange a handoff in a real deployment, but human transfer is not connected in this free demo.";
    if (/address|location|where/.test(text)) return "I don't have the business address configured yet. Add your address to this agent's business information so I can answer accurately.";
    if (/thank/.test(text)) return "You're welcome! Is there anything else I can help you with?";
    return "Thanks for your question. I'm running in free demo mode, so my answers are limited to a few sample topics. You can type or ask about opening hours, pricing, appointments, or speaking to a person.";
  }
  function answer(raw) {
    const q = (raw || "").trim();
    if (!q) return;
    log("You", q);
    const reply = localReply(q);
    log("Agent", reply);
    if ("speechSynthesis" in window) {
      window.speechSynthesis.cancel();
      const utterance = new SpeechSynthesisUtterance(reply);
      utterance.lang = "en-US";
      window.speechSynthesis.speak(utterance);
    }
  }
  async function loadAgents() {
    try {
      const agents = await api("/agents");
      $("talkAgent").innerHTML = agents.map(a =>
        `<option value="${a.id}">${escapeHtml(a.name)}${a.enabled ? "" : " (draft)"}</option>`
      ).join("") || '<option value="">Create an agent first</option>';
      $("talkStart").disabled = agents.length === 0;
    } catch (e) { state(e.message); }
  }
  function stop() {
    listening = false;
    if (recognition) { try { recognition.stop(); } catch {} recognition = null; }
    $("talkStart").disabled = false;
    $("talkStop").disabled = true;
    state("Demo ended");
  }
  function start() {
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SpeechRecognition) {
      state("Voice input unavailable");
      log("System", "Your browser does not support speech recognition. Use the message box and Send, or try a supported version of Chrome or Safari.");
      return;
    }
    listening = true;
    $("talkStart").disabled = true;
    $("talkStop").disabled = false;
    state("Listening…");
    recognition = new SpeechRecognition();
    recognition.lang = "en-US";
    recognition.continuous = false;
    recognition.interimResults = false;
    recognition.onresult = event => {
      const transcript = event.results?.[0]?.[0]?.transcript || "";
      answer(transcript);
      listening = false;
    };
    recognition.onerror = event => {
      state("Voice input issue");
      log("System", event.error === "not-allowed" ? "Microphone permission was denied. Allow microphone access in your browser settings." : "Speech recognition error: " + event.error + ". You can use the text box instead.");
      stop();
    };
    recognition.onend = () => {
      recognition = null;
      if (listening) { listening = false; $("talkStart").disabled = false; $("talkStop").disabled = true; state("Ready · Tap to speak again"); }
    };
    try { recognition.start(); } catch (e) { log("System", e.message); stop(); }
  }
  function startRecognitionAgain() {
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    recognition = new SpeechRecognition();
    recognition.lang = "en-US";
    recognition.continuous = false;
    recognition.interimResults = false;
    recognition.onresult = event => answer(event.results?.[0]?.[0]?.transcript || "");
    recognition.onerror = event => { log("System", "Speech recognition error: " + event.error); stop(); };
    recognition.onend = () => {
      recognition = null;
      if (listening) setTimeout(() => { if (listening) startRecognitionAgain(); }, 700);
    };
    recognition.start();
    state("Listening…");
  }
  $("talkStart").addEventListener("click", start);
  $("talkStop").addEventListener("click", stop);
  $("talkSend").addEventListener("click", () => { answer($("freeVoiceText").value); $("freeVoiceText").value = ""; });
  $("freeVoiceText").addEventListener("keydown", event => {
    if (event.key === "Enter") { answer($("freeVoiceText").value); $("freeVoiceText").value = ""; }
  });
  loadAgents();
  const originalRefresh = window.refreshAgents;
  if (typeof originalRefresh === "function") {
    window.refreshAgents = async function() { await originalRefresh(); await loadAgents(); };
  }
  document.addEventListener("visibilitychange", () => { if (document.hidden && listening) stop(); });
})();